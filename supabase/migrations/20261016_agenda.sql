-- Agenda: eventos del calendario, directorio de la fundación y lista de usuarios
-- para elegir invitados. Correr una sola vez en Supabase → SQL Editor.
-- Es idempotente: se puede volver a correr sin romper nada.

-- ¿El usuario actual es admin? (misma regla que registros/campañas)
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.perfiles where id = auth.uid() and rol = 'admin');
$$;

-- --- Eventos ---------------------------------------------------------------
-- inicio/fin en timestamptz. Los eventos de todo el día van de las 00:00 del
-- primer día a las 00:00 del día siguiente al último (fin exclusivo, como Google).
create table if not exists public.eventos (
  id             bigint generated by default as identity primary key,
  titulo         text        not null,
  descripcion    text,
  ubicacion      text,
  todo_el_dia    boolean     not null default false,
  inicio         timestamptz not null,
  fin            timestamptz not null,
  color          text        not null default 'maroon',
  invitados      text[]      not null default '{}',
  recordatorios  int[]       not null default '{1440}',  -- minutos antes del inicio
  registro_id    bigint,
  creado_por     uuid        default auth.uid(),
  creado_el      timestamptz not null default now(),
  actualizado_el timestamptz not null default now(),
  constraint eventos_fin_despues_de_inicio check (fin >= inicio)
);

create index if not exists eventos_inicio_idx on public.eventos (inicio);

alter table public.eventos enable row level security;

drop policy if exists "eventos: leer autenticados" on public.eventos;
create policy "eventos: leer autenticados" on public.eventos
  for select to authenticated using (true);

drop policy if exists "eventos: admin escribe" on public.eventos;
create policy "eventos: admin escribe" on public.eventos
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

create or replace function public.eventos_tocar_actualizado()
returns trigger language plpgsql as $$
begin
  new.actualizado_el := now();
  return new;
end;
$$;

drop trigger if exists eventos_actualizado on public.eventos;
create trigger eventos_actualizado before update on public.eventos
  for each row execute function public.eventos_tocar_actualizado();

-- --- Directorio --------------------------------------------------------------
-- Miembros del directorio que no necesariamente usan el panel pero pueden
-- recibir avisos de la agenda.
create table if not exists public.directorio (
  id        bigint generated by default as identity primary key,
  nombre    text        not null,
  email     text        not null unique,
  cargo     text,
  creado_el timestamptz not null default now()
);

alter table public.directorio enable row level security;

drop policy if exists "directorio: leer autenticados" on public.directorio;
create policy "directorio: leer autenticados" on public.directorio
  for select to authenticated using (true);

drop policy if exists "directorio: admin escribe" on public.directorio;
create policy "directorio: admin escribe" on public.directorio
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- --- Usuarios de la plataforma ----------------------------------------------
-- Los mails viven en auth.users, que no es accesible desde el navegador: esta
-- función expone solo email + rol, y solo a usuarios con sesión iniciada.
create or replace function public.usuarios_plataforma()
returns table (email text, rol text)
language sql
stable
security definer
set search_path = public, auth
as $$
  select u.email::text, p.rol::text
  from auth.users u
  join public.perfiles p on p.id = u.id
  where auth.uid() is not null and u.email is not null
  order by u.email;
$$;

revoke all on function public.usuarios_plataforma() from public, anon;
grant execute on function public.usuarios_plataforma() to authenticated;
